#!/usr/bin/env python3
"""
Generate Aria's adaptive-icon vectors from real Inter Display ExtraBold outlines.
Same system as the Minutia icon ("m:"): one cream letter + one coral round accent on ink.
Aria's mark is "a." — the letter plus a round period.

  pip install fonttools cairosvg pillow
  python3 docs/icon/make.py --font /usr/share/fonts/opentype/inter/InterDisplay-ExtraBold.otf --write
"""
import argparse, io, os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

X_HEIGHT_DP = 21.8   # ink height of the letter; matches Minutia's "m" so the two icons sit together
GAP_EM = 0.07        # space between letter and accent (same as Minutia)
BG, CREAM, CORAL = "#121614", "#F0ECDE", "#FF8A65"
ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
RES = os.path.join(ROOT, "app", "src", "main", "res")

def glyph(font, ch):
    gs = font.getGlyphSet(); name = font.getBestCmap()[ord(ch)]
    b = BoundsPen(gs); gs[name].draw(b)
    return gs, name, b.bounds, gs[name].width

def path(gs, name, tf):
    p = SVGPathPen(gs); gs[name].draw(TransformPen(p, tf)); return p.getCommands()

def build(fontfile):
    f = TTFont(fontfile); upm = f["head"].unitsPerEm
    ga, na, ba, _ = glyph(f, "a"); gp, np_, bp, _ = glyph(f, ".")
    s = X_HEIGHT_DP / (ba[3] - ba[1])
    gap = GAP_EM * upm
    # ink-based layout: letter ink, gap, period ink
    w_ink = (ba[2] - ba[0]) + gap + (bp[2] - bp[0])
    top = max(ba[3], bp[3]); bottom = min(ba[1], bp[1])
    ox = 54 - w_ink * s / 2; oy = 54 + (top + bottom) / 2 * s   # y flips
    ta = (s, 0, 0, -s, ox - ba[0] * s, oy)
    px = ox + ((ba[2] - ba[0]) + gap) * s - bp[0] * s
    tp = (s, 0, 0, -s, px, oy)
    return path(ga, na, ta), path(gp, np_, tp), (ox, ox + w_ink * s, oy - top * s, oy - bottom * s)

def vector(pa, pp, ca, cp, comment):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by docs/icon/make.py; don't hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{ca}" android:pathData="{pa}" />
    <path android:fillColor="{cp}" android:pathData="{pp}" />
</vector>
'''

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--font", required=True); ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    pa, pp, bounds = build(a.font)
    print("mark bounds x %.1f-%.1f y %.1f-%.1f" % bounds)
    svg = lambda bg, c1, c2: f'<svg xmlns="http://www.w3.org/2000/svg" width="432" height="432" viewBox="0 0 108 108"><rect width="108" height="108" fill="{bg}"/><path d="{pa}" fill="{c1}"/><path d="{pp}" fill="{c2}"/></svg>'
    import cairosvg
    from PIL import Image, ImageDraw
    def render(s):
        im = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=s.encode(), output_width=432, output_height=432))).convert("RGB")
        return im.crop((72, 72, 360, 360))
    full = render(svg(BG, CREAM, CORAL)); mono = render(svg("#D8E2FF", "#1B2A4A", "#1B2A4A"))
    T = 200; sheet = Image.new("RGB", (4 * (T + 30) + 30 + 78, T + 60), (60, 66, 62))
    def mask(n, shape):
        m = Image.new("L", (n, n), 0); d = ImageDraw.Draw(m)
        (d.ellipse((0, 0, n - 1, n - 1), fill=255) if shape == "c" else d.rounded_rectangle((0, 0, n - 1, n - 1), int(n * .28), fill=255)); return m
    for i, (im, sh) in enumerate([(full, "c"), (full, "s"), (mono, "c")]):
        sheet.paste(im.resize((T, T), Image.LANCZOS), (30 + i * (T + 30), 30), mask(T, sh))
    sheet.paste(full.resize((48, 48), Image.LANCZOS), (30 + 3 * (T + 30), 30 + T // 2 - 24), mask(48, "s"))
    out = os.path.join(os.path.dirname(__file__), "icon_preview.png"); sheet.save(out)
    icon = full.resize((256, 256), Image.LANCZOS).convert("RGBA"); icon.putalpha(mask(256, "s"))
    if a.write:
        icon.save(os.path.join(os.path.dirname(__file__), "icon.png")); icon.save(os.path.join(ROOT, "docs", "icon.png"))
        open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w").write(
            vector(pa, pp, "#FF" + CREAM[1:], "#FF" + CORAL[1:], 'Aria: Inter Display ExtraBold "a" in cream with a coral round period, on ink.'))
        open(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), "w").write(
            vector(pa, pp, "#FFFFFFFF", "#FFFFFFFF", "Themed-icon version: same two shapes, one colour; the launcher tints it."))
        print("written")
